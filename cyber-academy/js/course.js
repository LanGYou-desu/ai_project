GLOBAL_COMMANDS['quiz'] = async (toks) => {
  const n = parseInt(toks[1], 10);
  if (!n) {
    T.print('═══ 课后测验 ═══', 'header');
    COURSES.forEach((crs, i) => T.print(`  [${i + 1}] ${crs.title} (${crs.quiz.length} 题)`, 'cmd'));
    T.print('用法: quiz <编号>', 'cmd');
    return;
  }
  const crs = COURSES[n - 1];
  if (!crs) { T.print('编号无效。', 'error'); return; }
  T.print(`═══ 测验: ${crs.title} (${crs.quiz.length} 题) ═══`, 'header');
  const alreadyDone = Game.quizzesDone.has(crs.id);
  let correct = 0;
  for (const q of crs.quiz) {
    T.print('问题: ' + q.q, 'normal');
    q.options.forEach((o, i) => T.print(`  ${String.fromCharCode(97 + i)}) ${o}`, 'cmd'));
    const ans = (await askLine('答案 (a/b/c/d): ')).trim().toLowerCase();
    let idx = -1;
    if (ans.length === 1 && ans >= 'a' && ans <= 'd') idx = ans.charCodeAt(0) - 97;
    else idx = parseInt(ans, 10) - 1;
    if (idx === q.answer) {
      correct++;
      T.print('✔ 正确!', 'success');
      Sound.ok();
    } else {
      T.print(`✘ 错误。正确答案: ${String.fromCharCode(97 + q.answer)}) ${q.options[q.answer]}`, 'error');
      Sound.err();
      // 记入错题本
      Game.mistakes.push({
        type: 'quiz', courseId: crs.id, courseTitle: crs.title,
        q: q.q, your: idx >= 0 && idx < 4 ? q.options[idx] : ('(无效输入: ' + ans + ')'),
        correct: q.options[q.answer], explain: q.explain,
      });
      Game.mistakesTotal++;
    }
    T.print('  讲解: ' + q.explain, 'dim');
    T.newline();
  }
  const total = crs.quiz.length;
  const passed = correct >= Math.ceil(total / 2);
  T.print(`测验完成: ${correct}/${total} — ${passed ? '通过!' : '未通过，可重试'}`, passed ? 'success' : 'info');
  if (passed && !alreadyDone) {
    Game.quizzesDone.add(crs.id);
    award(60, `完成课程测验: ${crs.title}`);
    if (Game.quizzesDone.size >= COURSES.length) unlockAchievement('quiz_master');
    unlockAchievement('student');
  } else if (passed && alreadyDone) {
    T.print('(本测验已通过过，复习不计分 — 防刷分)', 'dim');
  }
  // 首次通过才计得分; 未通过也可重试但同样仅首次得分
  if (!alreadyDone && passed) award(correct * 20, '测验得分');
  else if (!alreadyDone) T.print('(通过后才能获得本测验得分)', 'dim');
  Game.save();
};
