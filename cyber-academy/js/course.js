function printChapterLines(lines) {
  for (const raw of lines) {
    if (raw.startsWith('# ')) T.print(raw.slice(2), 'header');
    else if (raw.startsWith('> ')) T.print(raw.slice(2), 'cmd');
    else if (raw.startsWith('! ')) T.print(raw.slice(2), 'info');
    else if (raw.startsWith('$ ')) T.print(raw.slice(2), 'hint');
    else T.print(raw, 'normal');
  }
}

