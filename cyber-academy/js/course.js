/* 选项乱序: 避免"正确答案全在 A"的缺陷, 确定性打散答案分布 */
COURSES.forEach((c) => {
  c.quiz.forEach((q, qi) => {
    const correct = q.options[q.answer];
    const shift = (c.id * 3 + qi) % q.options.length;
    const rotated = [];
    for (let i = 0; i < q.options.length; i++) rotated.push(q.options[(i + shift) % q.options.length]);
    q.options = rotated;
    q.answer = rotated.indexOf(correct);
  });
});

