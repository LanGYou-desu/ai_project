  function hashStr(s) { var h = 0; for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0; return h; }

  // 兜底：任意词生成确定性的抽象纹理
  function squiggle(word) {
    var g = G();
    var h = hashStr(word);
    var n = 6 + (h % 5);
    var x = 0.2, y = 0.3 + (h % 4) * 0.1;
    for (var i = 0; i < n; i++) {
      var x2 = 0.2 + (i + 1) * 0.6 / n;
      var y2 = 0.25 + ((h >> (i * 3)) % 40) / 100;
      L(g, x, y, x2, y2);
      x = x2; y = y2;
    }
    return g;
  }

